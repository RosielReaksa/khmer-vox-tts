#!/usr/bin/env node
/**
 * install-hooks.mjs
 * 
 * Installs a git pre-commit hook that runs the mojibake detector on staged
 * source files. If mojibake is detected, the commit is blocked.
 * 
 * Usage:
 *   node scripts/install-hooks.mjs        # install the hook
 *   node scripts/install-hooks.mjs --check # verify hook is installed
 *   node scripts/install-hooks.mjs --remove # remove the hook
 */

import { readFileSync, writeFileSync, existsSync, chmodSync, unlinkSync, rmSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(__dirname, "..");
const hooksDir = resolve(projectRoot, ".git", "hooks");
const hookPath = resolve(hooksDir, "pre-commit");

const HOOK_SCRIPT = `#!/bin/sh
# Git pre-commit hook — mojibake detection
# Auto-generated by scripts/install-hooks.mjs
# Blocks commits containing double/triple-encoded UTF-8 in source files.

# Run the detector on staged files
node scripts/detect-mojibake.mjs --staged
exit $?
`;

function install() {
  // Ensure hooks directory exists
  if (!existsSync(hooksDir)) {
    console.error("Error: .git/hooks directory not found. Is this a git repo?");
    process.exit(1);
  }

  // Write the hook
  writeFileSync(hookPath, HOOK_SCRIPT, { encoding: "utf-8", mode: 0o755 });
  
  // Ensure executable (Windows doesn't respect shebang, but chmod for Unix)
  try {
    chmodSync(hookPath, 0o755);
  } catch {
    // Windows — chmod is a no-op, but the .js extension association handles it
  }

  console.log("✓ Pre-commit hook installed.");
  console.log(`  Location: ${hookPath}`);
  console.log("  Effect: blocks commits with mojibake in staged .ts/.tsx/.js/.mjs/.md files.");
  console.log("");
  console.log("  To bypass in an emergency: git commit --no-verify");
}

function check() {
  if (!existsSync(hookPath)) {
    console.log("✗ Pre-commit hook NOT installed.");
    console.log("  Run: node scripts/install-hooks.mjs");
    process.exit(1);
  }

  const content = readFileSync(hookPath, "utf-8");
  if (content.includes("detect-mojibake")) {
    console.log("✓ Pre-commit hook is installed and active.");
  } else {
    console.log("⚠ Hook file exists but doesn't contain mojibake check.");
    process.exit(1);
  }
}

function remove() {
  if (existsSync(hookPath)) {
    unlinkSync(hookPath);
    console.log("✓ Pre-commit hook removed.");
  } else {
    console.log("No hook to remove.");
  }
}

// --- Main ---
const args = process.argv.slice(2);

if (args.includes("--check")) {
  check();
} else if (args.includes("--remove")) {
  remove();
} else {
  install();
}
